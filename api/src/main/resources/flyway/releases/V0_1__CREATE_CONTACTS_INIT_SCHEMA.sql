CREATE TABLE CONTACT (
     CONTACT_UUID            UUID            NOT NULL,
     CONTACT_FIRST_NAME      VARCHAR(100)    NOT NULL,
     CONTACT_LAST_NAME       VARCHAR(100),
     ADDRESS                 VARCHAR(255),
     BIRTH_DATE              DATE,
     CONSTRAINT PK_CONTACT PRIMARY KEY (CONTACT_UUID)
);

CREATE TABLE CONTACT_PHONE_NUMBER (
      CONTACT_UUID            UUID            NOT NULL,
      PHONE_NUMBER            VARCHAR(50)     NOT NULL,
      CONSTRAINT PK_CONTACT_PHONE_NUMBER PRIMARY KEY (CONTACT_UUID, PHONE_NUMBER),
      CONSTRAINT FK_CONTACT_PHONE_CONTACT FOREIGN KEY (CONTACT_UUID)
          REFERENCES CONTACT (CONTACT_UUID) ON DELETE CASCADE
);

CREATE TABLE CONTACT_EMAIL (
       CONTACT_UUID            UUID            NOT NULL,
       EMAIL                   VARCHAR(255)    NOT NULL,
       CONSTRAINT PK_CONTACT_EMAIL PRIMARY KEY (CONTACT_UUID, EMAIL),
       CONSTRAINT FK_CONTACT_EMAIL_CONTACT FOREIGN KEY (CONTACT_UUID)
           REFERENCES CONTACT (CONTACT_UUID) ON DELETE CASCADE
);